// French typography: a narrow no-break space before ? ! ; : and inside « » (so they never
// start a line on their own)
const NB = ' ';
const fixFr = v => typeof v === 'string'
  ? v.replace(/ ([?!;:])/g, NB + '$1').replace(/« /g, '«' + NB).replace(/ »/g, NB + '»')
  : Array.isArray(v) ? v.map(fixFr) : v && typeof v === 'object' ? Object.fromEntries(Object.entries(v).map(([k, x]) => [k, fixFr(x)])) : v;

export default fixFr(fr);
